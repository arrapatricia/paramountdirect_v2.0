// Real barangay list for the given city, "N/A" prepended so it's still
// selectable for addresses that don't have one on file (rural delivery
// addresses, foreign-facing forms, etc.) - falls back to the generic
// placeholder list for any city not in CITY_BARANGAYS.
export function barangaysForCity(cityName: string): string[] {
  const real = CITY_BARANGAYS[cityName];
  return real ? ['N/A', ...real] : GENERIC_BARANGAYS;
}
