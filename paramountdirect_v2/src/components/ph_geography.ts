// Shared Philippine region/city/barangay data for address dropdowns across
// OFW, CTPL, and PD Life create-application forms. All 17 official regions
// are covered, each with its major cities/municipalities - not every single
// city or municipality in the country, but enough that a real applicant's
// city is almost always on the list.
//
// Barangay lists are real, sourced from the PSGC (Philippine Standard
// Geographic Code) via https://github.com/isaacdarcilla/philippine-addresses
// (2026-09-30 snapshot) - not hand-typed placeholders. A few notes on the
// source data:
// - Manila City has no single PSGC entry - it's recorded as its 14
//   individual pre-war districts (Tondo, Binondo, Quiapo, etc.), so its
//   897 barangays here are the union of all of them.
// - Where a city/municipality name collides with another of the same name
//   elsewhere in the country (e.g. "Naga" in both Camarines Sur and Cebu),
//   the match was resolved by the region (and, for a few, the province)
//   the real city actually belongs to, not just a name match.

