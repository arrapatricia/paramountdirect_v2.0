const HIP_GRID_BY_OPTION: Record<HipInsuredOption, Record<HipPaymentMode, HipGrid>> = {
  Individual: HIP_INDIVIDUAL,
  'Married Couple': HIP_COUPLE,
  Family: HIP_FAMILY,
};

export function getHipPremium(insuredOption: HipInsuredOption, age: number, tier: number, mode: HipPaymentMode): number {
  const bandIdx = findAgeBandIndex(age, HIP_AGE_BANDS);
  const tierIdx = Math.max(0, HIP_TIERS.indexOf(tier));
  return HIP_GRID_BY_OPTION[insuredOption][mode][bandIdx][tierIdx];
}
